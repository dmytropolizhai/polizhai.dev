/**
 * Exports portfolio content from `getSiteContent("en")` into `functions/_generated/knowledge.ts`
 * so the Cloudflare Pages Functions AI assistant stays in sync with the built site.
 */
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { defaultLocale, facts as defaultFacts, urls } from "../content/site.ts";
import { caseStudyPagesLive } from "../src/lib/pending.ts";
import { isSanityConfigured } from "../src/sanity/env.ts";
import { getSiteContent } from "../src/sanity/lib/fetch.ts";
import { assertSafeKnowledge, buildKnowledgeMarkdown } from "./knowledge-lib.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, "..");
const outFile = resolve(rootDir, "functions/_generated/knowledge.ts");

function loadEnvIfExists(filename: string) {
  const fullPath = resolve(rootDir, filename);
  if (!existsSync(fullPath)) return;
  if (typeof process.loadEnvFile === "function") {
    process.loadEnvFile(fullPath);
  }
}

async function main() {
  loadEnvIfExists(".env");
  loadEnvIfExists(".env.local");

  const content = await getSiteContent(defaultLocale);
  const markdown = buildKnowledgeMarkdown(content, {
    telegramUrl: urls.telegram,
    caseStudyPagesLive,
    asOf: defaultFacts.asOf,
  });

  const { approxTokens, warning } = assertSafeKnowledge(markdown);
  if (warning) {
    console.warn(`[build-knowledge] WARNING: ${warning}`);
  }

  const meta = {
    generatedAt: new Date().toISOString(),
    asOf: defaultFacts.asOf,
    approxTokens,
    source: isSanityConfigured ? ("sanity" as const) : ("defaults" as const),
  };

  const output = `// AUTO-GENERATED by scripts/build-knowledge.ts — do not edit manually.
export const knowledge: string = ${JSON.stringify(markdown)};

export const knowledgeMeta = ${JSON.stringify(meta, null, 2)} as const;
`;

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, output, "utf8");
  console.log(
    `[build-knowledge] Generated ${outFile} (${approxTokens} approx tokens, source=${meta.source})`,
  );
}

main().catch((err) => {
  console.error("[build-knowledge] FAILED:", err instanceof Error ? err.message : err);
  process.exit(1);
});
